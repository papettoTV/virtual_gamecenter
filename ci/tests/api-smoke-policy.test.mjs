import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { parse } from 'yaml';
test('API smoke is human-gated, manual-only, uses an empty directory and keeps the API key out of shell steps', async () => {
  const workflow = parse(await readFile(new URL('../../.github/workflows/codex-api-smoke.yml', import.meta.url), 'utf8'));
  assert.deepEqual(Object.keys(workflow.on), ['workflow_dispatch']);
  const probe = workflow.jobs.probe;
  assert.equal(probe.environment, 'codex');
  assert.match(probe.if, /refs\/heads\/develop/);
  assert.match(probe.if, /papettoTV/);
  assert.ok(!probe.env);
  const action = probe.steps.at(-1);
  assert.match(action.uses, /^openai\/codex-action@[a-f0-9]{40}$/);
  assert.equal(action.with.sandbox, 'read-only');
  assert.equal(action.with['safety-strategy'], 'drop-sudo');
  assert.equal(action.with['working-directory'], '${{ runner.temp }}/pulbase-codex-smoke');
  assert.equal(action.with['openai-api-key'], '${{ secrets.OPENAI_API_KEY }}');
  assert.match(action.with.prompt, /exactly CODEX_API_OK/);
  assert.ok(probe.steps.slice(0, -1).every(step => !JSON.stringify(step).includes('secrets.')));
  assert.deepEqual(workflow.jobs.confirm.needs, 'probe');
  assert.ok(!JSON.stringify(workflow.jobs.confirm).includes('secrets.'));
});
